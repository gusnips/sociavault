// Reads openapi.json and writes src/schema.d.ts, src/modules/*.ts and src/client.ts.
// Run it with `bun run generate`. Never edit the files it writes.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";

interface Parameter {
  name: string;
  required?: boolean;
}

interface Operation {
  summary?: string;
  description?: string;
  tags: string[];
  parameters?: Parameter[];
}

interface Doc {
  paths: Record<string, { get: Operation }>;
}

const SPEC_FILE = "openapi.json";
const CLIENT_CLASS = "SociaVaultClient";
const HEADER =
  "// Generated by scripts/generate.ts from openapi.json. Do not edit.\n";
const SCRAPE_PREFIX = "/v1/scrape/";

// Whole sample responses are hundreds of lines each, so they go. Short examples, like a handle,
// stay. SociaVault's text uses a long dash for a clause break, and it lands in comments people
// read, so a colon takes its place.
function prune(key: string, value: unknown): unknown {
  const isSampleResponse =
    (key === "example" || key === "examples") &&
    typeof value === "object" &&
    value !== null;
  if (isSampleResponse) return undefined;
  const isText = key === "description" || key === "summary";
  return isText && typeof value === "string"
    ? value.replaceAll(" \u2014 ", ": ")
    : value;
}

const text = readFileSync(SPEC_FILE, "utf8");
const spec: OpenAPI3 = JSON.parse(text, prune);
const doc: Doc = JSON.parse(text, prune);

function words(name: string): string[] {
  return name.split(/[^a-zA-Z0-9]+/).filter(Boolean);
}

function pascalCase(name: string): string {
  return words(name)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join("");
}

function camelCase(name: string): string {
  const pascal = pascalCase(name);
  return pascal[0].toLowerCase() + pascal.slice(1);
}

// "/v1/scrape/tiktok/search/users" is `tiktok.searchUsers`: the group is the platform and the
// method is the rest of the path. The one path outside /v1/scrape/ (/v1/credits) sits in the
// group of its tag.
function locate(op: Operation, path: string): { group: string; name: string } {
  if (!path.startsWith(SCRAPE_PREFIX)) {
    return {
      group: camelCase(op.tags[0]),
      name: camelCase(path.replace("/v1/", "")),
    };
  }
  const [platform, ...rest] = path.slice(SCRAPE_PREFIX.length).split("/");
  return { group: camelCase(platform), name: camelCase(rest.join("/")) };
}

function docComment(op: Operation): string {
  const prose = [op.summary, op.description].filter(Boolean).join("\n\n");
  const text = prose.replaceAll("*/", "*\\/");
  return `/**\n${text
    .split("\n")
    .map((line) => ` * ${line}`.trimEnd())
    .join("\n")}\n */`;
}

interface Method {
  name: string;
  path: string;
  op: Operation;
}

const groups = new Map<string, Method[]>();
for (const [path, { get: op }] of Object.entries(doc.paths)) {
  const { group, name } = locate(op, path);
  const methods = groups.get(group) ?? [];
  if (methods.some((method) => method.name === name)) {
    throw new Error(
      `Two operations in "${group}" are named "${name}". Rename one in locate.`,
    );
  }
  methods.push({ name, path, op });
  groups.set(group, methods);
}

function renderMethod({ name, path, op }: Method): string {
  const params = op.parameters ?? [];
  const args = ["options?: CallOptions"];
  let init = "{ signal: options?.signal }";
  if (params.length) {
    const optional = params.some((param) => param.required) ? "" : "?";
    args.unshift(`query${optional}: Query<"${path}">`);
    init = "{ params: { query }, signal: options?.signal }";
  }
  return `${docComment(op)}\n${name}(${args.join(", ")}) {\n  return unwrap(this.api.GET("${path}", ${init}));\n}`;
}

function renderModule(group: string, methods: Method[]): string {
  const needsQuery = methods.some(({ op }) => op.parameters?.length);
  const httpImports = needsQuery
    ? "unwrap, type CallOptions, type Query"
    : "unwrap, type CallOptions";
  return `${HEADER}import type { Client } from "openapi-fetch";
import { ${httpImports} } from "../http";
import type { paths } from "../schema";

export class ${pascalCase(group)}Module {
  constructor(private readonly api: Client<paths>) {}

${methods.map(renderMethod).join("\n\n")}
}
`;
}

function renderClient(groupNames: string[]): string {
  const modules = groupNames.map((name) => ({
    name,
    className: `${pascalCase(name)}Module`,
  }));
  return `${HEADER}import type { Client } from "openapi-fetch";
import { createApi, type SociaVaultConfig } from "./http";
${modules.map(({ name, className }) => `import { ${className} } from "./modules/${name}";`).join("\n")}
import type { paths } from "./schema";

export class ${CLIENT_CLASS} {
  readonly api: Client<paths>;
${modules.map(({ name, className }) => `  readonly ${name}: ${className};`).join("\n")}

  constructor(config: SociaVaultConfig | string) {
    this.api = createApi(typeof config === "string" ? { apiKey: config } : config);
${modules.map(({ name, className }) => `    this.${name} = new ${className}(this.api);`).join("\n")}
  }
}
`;
}

rmSync("src/modules", { recursive: true, force: true });
mkdirSync("src/modules", { recursive: true });
writeFileSync("src/schema.d.ts", astToString(await openapiTS(spec)));
for (const [group, methods] of groups) {
  writeFileSync(`src/modules/${group}.ts`, renderModule(group, methods));
}
writeFileSync("src/client.ts", renderClient([...groups.keys()]));
console.log(
  [...groups]
    .map(([group, methods]) => `${group}: ${methods.length}`)
    .join(", "),
);
